// Standalone browser check, not part of the dependency-free Node test glob.
// Supply PLAYWRIGHT_MODULE if Playwright is installed in an isolated tools folder.
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const output = process.env.ARTIFACT_DIR ?? 'outputs/browser-smoke';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: { width: 1360, height: 960 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', dialog => dialog.accept());
const go = async name => page.getByRole('navigation').getByRole('button', { name: new RegExp(name) }).click();
try {
  await page.goto(process.env.APP_URL ?? 'http://127.0.0.1:4173', { waitUntil: 'networkidle' });
  await go('Instellingen');
  await page.getByLabel('Kenteken (demo)', { exact: true }).fill('TEST-42');
  await page.getByRole('button', { name: 'Kenteken toepassen', exact: true }).click();
  await page.getByLabel('Tarief vanaf', { exact: true }).fill('2026-01-01');
  await page.getByLabel('Tarief tot en met (optioneel)', { exact: true }).fill('2026-12-31');
  await page.getByLabel('Bedrag euro per km', { exact: true }).fill('0.25');
  await page.getByRole('button', { name: 'Tarief toevoegen', exact: true }).click();
  await page.getByLabel('Naam voorkeursadres', { exact: true }).fill('Testadres');
  await page.getByLabel('Voorkeursadres', { exact: true }).fill('Teststraat 1');
  await page.getByLabel('Adresnotitie', { exact: true }).fill('Uitsluitend synthetische test');
  await page.getByRole('button', { name: 'Demoadres toevoegen', exact: true }).click();
  await page.getByRole('button', { name: 'Uitschakelen', exact: true }).click();
  assert.match(await page.locator('.settings-layout').innerText(), /Uitgeschakeld/);
  await go('Mijn Jeep');
  assert.match(await page.locator('.vehicle-details').innerText(), /TEST-42/);
  await go('Rapporten');
  await page.getByRole('button', { name: 'Rapport maken', exact: true }).click();
  assert.match(await page.locator('.print-report').innerText(), /TEST-42/);
  assert.match(await page.locator('.print-report').innerText(), /14,93/);
  assert.equal(await page.locator('.report-data tbody tr').count(), 5);
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'CSV downloaden', exact: true }).click();
  const download = await downloaded;
  const csvPath = path.join(output, 'report.csv'); await download.saveAs(csvPath);
  const csv = await readFile(csvPath, 'utf8');
  assert.ok(csv.includes('"TEST-42"')); assert.ok(csv.includes('NIET VOOR FISCALE INDIENING'));
  await go('Instellingen');
  await page.getByRole('button', { name: 'Tarief bewerken', exact: true }).click();
  await page.getByLabel('Bedrag euro per km', { exact: true }).fill('0.50');
  await page.getByRole('button', { name: 'Tariefwijziging toepassen', exact: true }).click();
  await go('Rapporten');
  assert.match(await page.locator('.print-report').innerText(), /14,93/);
  await page.getByRole('button', { name: 'Rapport maken', exact: true }).click();
  assert.match(await page.locator('.print-report').innerText(), /29,85/);
  await page.getByLabel('Eerder gemaakt demorapport', { exact: true }).selectOption('0');
  assert.match(await page.locator('.print-report').innerText(), /14,93/);
  await page.screenshot({ path: path.join(output, 'reports-desktop.png'), fullPage: true });
  await page.pdf({ path: path.join(output, 'report.pdf'), preferCSSPageSize: true });
  assert.equal((await readFile(path.join(output, 'report.pdf'))).subarray(0, 5).toString(), '%PDF-');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Wissel kleurthema', exact: true }).click();
  assert.equal(await page.locator('main.sand').count(), 1);
  await page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page must not overflow viewport');
  await page.screenshot({ path: path.join(output, 'reports-mobile-sand.png'), fullPage: true });
  await go('Kaarten');
  await page.getByLabel('Rit voor routeoverzicht', { exact: true }).selectOption('2');
  const url = await page.getByRole('link', { name: 'Route berekenen in Apple Kaarten' }).getAttribute('href');
  assert.match(decodeURIComponent(url), /saddr=Amersfoort&daddr=Utrecht/);
  await go('Ritten');
  await page.getByRole('button', { name: 'Rit bewerken', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Voorbeeldrit corrigeren' }).count(), 1);
  await page.getByRole('button', { name: 'Annuleren', exact: true }).click();
  await page.getByRole('button', { name: 'Handmatige voorbeeldrit', exact: true }).click();
  await page.getByLabel('Begintijd', { exact: true }).fill('15:00');
  await page.getByLabel('Eindtijd', { exact: true }).fill('15:30');
  await page.getByLabel('Vertrek', { exact: true }).fill('Testbegin');
  await page.getByLabel('Bestemming', { exact: true }).fill('Testeinde');
  await page.getByLabel('Afstand (km)', { exact: true }).fill('5');
  await page.getByLabel('Registratietoelichting', { exact: true }).fill('Uitsluitend synthetische handmatige test');
  await page.getByRole('button', { name: 'Voorbeeldrit toevoegen', exact: true }).click();
  assert.match(await page.locator('.detail-panel').innerText(), /Testbegin → Testeinde/);
  assert.match(await page.locator('.detail-panel').innerText(), /Onbekend/);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: ['plate', 'rates', 'addresses', 'historical snapshots', 'CSV download', 'print PDF', 'mobile theme/layout', 'map handoff', 'trip editor', 'manual trip'], browser: await browser.version(), artifacts: output }));
} finally { await browser.close(); }
